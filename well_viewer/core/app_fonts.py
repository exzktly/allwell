"""Bundled application fonts (Inter UI + JetBrains Mono numeric).

The app previously inherited each platform's default UI face
(``QApplication.font().family()`` — Segoe UI / SF / DejaVu), so it looked
different on every OS and the weakest on Linux. Bundling the fonts makes the
chrome identical everywhere and lets the matplotlib plots match the UI (which
also removes the legacy ``Font family 'Helvetica' not found`` fallback).

Inter and JetBrains Mono ship as **static** single-weight instances (Regular /
Medium / SemiBold / Bold for the UI face; Regular / Bold for mono). The upstream
*variable* TTFs are also kept in-repo as the regeneration source
(``scripts/make_static_fonts.py``) but are not registered: Qt's
``addApplicationFont`` loads variable fonts unreliably on Windows (the family
silently fails to register and the app falls back to the platform default),
whereas the static instances load consistently everywhere and Qt groups them
under one family, resolving weights via ``QFont.setWeight``.

All faces are SIL OFL licensed (see ``assets/fonts/*-OFL.txt``), so they can be
redistributed with the app.
"""
from __future__ import annotations

import sys
from pathlib import Path

# Static weight instances, Regular first (its family name is the canonical one
# the other weights group under). Generated by ``scripts/make_static_fonts.py``.
UI_FONT_FILES = (
    "Inter-Regular.ttf",
    "Inter-Medium.ttf",
    "Inter-SemiBold.ttf",
    "Inter-Bold.ttf",
)
MONO_FONT_FILES = ("JetBrainsMono-Regular.ttf", "JetBrainsMono-Bold.ttf")
# Variable sources — fallback only if the static instances are missing.
UI_FONT_FALLBACK = "Inter.ttf"
MONO_FONT_FALLBACK = "JetBrainsMono.ttf"


def fonts_dir() -> Path:
    """Locate ``assets/fonts`` both in-repo and inside a PyInstaller bundle."""
    base = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parents[2]))
    return base / "assets" / "fonts"


def _register_qt_group(d: Path, files: tuple[str, ...], fallback: str) -> str:
    """Register every weight file in *files*; return the base family name.

    The base family (e.g. ``"Inter"``) is whatever the first (Regular) face
    registers under — Qt groups the heavier weights beneath it and resolves
    them through ``QFont.setWeight``. Falls back to the variable source if no
    static instance loaded.
    """
    from PySide6.QtGui import QFontDatabase

    base = ""
    loaded = False
    for fname in files:
        fpath = d / fname
        if not fpath.exists():
            continue
        fid = QFontDatabase.addApplicationFont(str(fpath))
        fams = QFontDatabase.applicationFontFamilies(fid) if fid != -1 else []
        if fams:
            loaded = True
            if not base:
                base = fams[0]
    if loaded:
        return base
    fpath = d / fallback
    if fpath.exists():
        fid = QFontDatabase.addApplicationFont(str(fpath))
        fams = QFontDatabase.applicationFontFamilies(fid) if fid != -1 else []
        if fams:
            return fams[0]
    return ""


def register_qt_fonts() -> tuple[str, str]:
    """Register the bundled fonts with Qt's font database.

    Returns ``(ui_family, mono_family)`` — the registered family names, or an
    empty string for any face that is missing / failed to load so the caller
    can fall back to the platform default.
    """
    d = fonts_dir()
    return (
        _register_qt_group(d, UI_FONT_FILES, UI_FONT_FALLBACK),
        _register_qt_group(d, MONO_FONT_FILES, MONO_FONT_FALLBACK),
    )


def register_mpl_ui_font() -> str:
    """Register the bundled UI font weights with matplotlib's font manager.

    Returns the family name (``"Inter"``) on success, else ``""``. Called
    lazily from the plot-styling layer so matplotlib stays out of the startup
    path. Idempotent-friendly: matplotlib dedupes repeated ``addfont`` calls.
    """
    d = fonts_dir()
    try:
        from matplotlib import font_manager as _fm
        from matplotlib.font_manager import FontProperties
    except Exception:
        return ""
    name = ""
    for fname in UI_FONT_FILES:
        fpath = d / fname
        if not fpath.exists():
            continue
        try:
            _fm.fontManager.addfont(str(fpath))
            if not name:
                name = FontProperties(fname=str(fpath)).get_name()
        except Exception:
            from well_viewer.core.safe import swallowed
            swallowed()  # one weight failing shouldn't abort the rest
    if name:
        return name
    fpath = d / UI_FONT_FALLBACK
    if fpath.exists():
        try:
            _fm.fontManager.addfont(str(fpath))
            return FontProperties(fname=str(fpath)).get_name()
        except Exception:
            return ""
    return ""
