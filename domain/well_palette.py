"""The 96 well-rank colours, and nothing else.

A selection's colour is *baked from the rank of its lowest well* and then
written into the ``color`` field of the ``sample_definitions`` block on disk.
Review bakes it when a person makes a selection; Datasets re-bakes it when
``merge_plates`` moves a condition to a different part of the plate. The two
panes therefore have to hold the same 96 values or the same well writes two
different colours into the same file, so this is shared subject matter rather
than screen chrome — which is why it sits here, below every GUI layer, instead
of in :mod:`ui.theme`.

:mod:`ui.theme` re-exports it under the same name, so every reader that has
always said ``theme.WELL_COLORS_TUPLE`` still does. This module imports
nothing.

Generated by ``_Docs/design/well_palette_build.py``, which reproduces every
figure below. Ranks 0 to 7 are eight colours chosen by hand and approved; the
other 88 were chosen and placed by the script so that every colour clears 3 : 1
on the grey plot background, and the wells a person selects together — the next
well along a row or down a column — stay far apart for normal vision and for
deuteranopia and protanopia (Machado et al. 2009, full severity). Measured, in
OKLab distance times 100: no colour under 3 : 1 on the grey plot background
(lowest 3.34), three under it on the blue (lowest 2.99), eighteen on white for
exported figures (lowest 2.75, set by the approved yellow); plate neighbours at
least 14.0 apart for normal vision and 10.1 colour-blind, none under 8; two wells
far apart on the plate as close as 4.0. ``tests/test_well_palette.py``
recomputes each figure. The palette leans to blues, purples and pinks because a
bright yellow or green cannot reach 3 : 1 on white.

**A colour already written to a dataset is kept.** Changing this list changes
what a selection made from now on is baked with; a selection whose colour is
already saved in a dataset's ``sample_definitions`` keeps it (``rank_color`` runs
only when no colour is stored), so a dataset can show old and new colours side by
side. There is no migration, by decision.

Three consumers reference it:

* :data:`ui.theme.Colors.trace` / :data:`ui.theme.CPub.trace` — what
  ``widgets/plot_card.plot_palette()`` feeds into matplotlib's
  ``axes.prop_cycle`` (screen and publication modes alike).
* ``review.domain.plate_layout.WELL_COLORS`` — a plain ``list()`` copy, read by
  every plot renderer that needs a per-well colour by rank. Named here as a
  reader, which is the direction that is allowed: nothing in this package
  imports it, and this module imports nothing at all.
* :func:`domain.selections_format.well_colors` — the palette ``rank_color``
  bakes from.

NOTE — the length must be **96** (one colour per 96-well plate position), not a
submultiple of it. Well colour is ``WELL_COLORS[well_rank(token) % len]`` and
ranks step by 12 (the column count) going *down* a plate column, so any length
that divides a multiple of 12 within one column (e.g. 48 = 4x12) makes the
colours visibly repeat down each column — rows E-H mirror A-D in "sets of
four". 96 distinct entries give every well its own colour and remove the wrap.
"""

