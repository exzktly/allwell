#!/usr/bin/env python3
"""Generate a per-profile pip requirements file — the pip half of feature gating.

The PyInstaller build already drops a profiled-out feature's heavy deps from the
*bundle* (``all_well.spec`` adds ``full.toml``'s ``deps`` to ``excludes``). This
script is the dev-install counterpart: it emits a flat requirements file for a
profile with the excluded features' PyPI packages removed, so installing a thin
profile never pip-installs the packages it can't use.

    # Print the thin profile's install set (drops torch/torchvision/cellpose):
    python scripts/gen_requirements.py --profile thin

    # Write it out for a StarDist-only remote:
    python scripts/gen_requirements.py --profile thin -o requirements-thin.txt
    pip install --no-build-isolation -r requirements-thin.txt

What it drops: the ``pip`` distribution names of every catalog feature the
profile does not admit (``profiles/full.toml``). A feature with no ``pip`` field
(most of them are pure-Python and add nothing to the install) drops nothing.

The base file's ``-r other.txt`` includes are followed and inlined, so the
output is a single self-contained file — matching how ``requirements.txt`` pulls
in ``requirements-remote.txt``. Dropped lines are emitted as comments (not
deleted) so the output stays auditable: you can see exactly what the profile
removed and why.

Stdlib-only; mirrors ``derive_profile.py``'s profile-inclusion predicate so the
pip set and the stripped tree always agree.
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path
from types import SimpleNamespace


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _normalize(dist: str) -> str:
    """PEP 503 name normalization: lower-case, runs of -_. collapse to one -."""
    return re.sub(r"[-_.]+", "-", dist.strip().lower())


def _dist_name(line: str) -> "str | None":
    """The distribution name a requirement *line* installs, or ``None`` for a
    non-requirement line (blank / comment / ``-r`` include / bare option).

    Handles version specifiers, extras (``pkg[extra]``), and environment markers
    (``pkg ; sys_platform == 'darwin'``) — everything before the first of
    ``[ < > = ! ~ ;`` and surrounding whitespace is the name."""
    s = line.strip()
    if not s or s.startswith("#") or s.startswith("-"):
        return None
    m = re.match(r"^([A-Za-z0-9._-]+)", s)
    return m.group(1) if m else None


def excluded_pip_names(catalog: list, profile) -> set:
    """Normalized PyPI names to drop: the ``pip`` lists of every catalog feature
    the *profile* rejects (same predicate the runtime filter / derive uses)."""
    drop: set = set()
    for entry in catalog:
        shim = SimpleNamespace(name=str(entry.get("name") or ""),
                               parent=str(entry.get("parent") or ""))
        if profile.includes(shim):
            continue
        for dist in entry.get("pip") or []:
            drop.add(_normalize(str(dist)))
    return drop


def _iter_lines(path: Path, seen: set):
    """Yield ``(source_line, origin_path)`` for *path*, inlining ``-r`` includes.

    ``seen`` guards against an include cycle. Missing includes raise (a typo in a
    requirements file should fail loudly, not silently skip a whole dep group)."""
    real = path.resolve()
    if real in seen:
        return
    seen.add(real)
    for raw in path.read_text(encoding="utf-8").splitlines():
        stripped = raw.strip()
        m = re.match(r"^(?:-r|--requirement)\s+(.+)$", stripped)
        if m:
            inc = (path.parent / m.group(1).strip()).resolve()
            yield f"# ── inlined from {inc.name} ──", path
            yield from _iter_lines(inc, seen)
            continue
        yield raw, path


def generate(base: Path, catalog: list, profile, drop: set) -> str:
    """Return the profile's flat requirements text: *base* with its includes
    inlined and every line installing a dropped distribution commented out."""
    admitted = None if profile.features is None else sorted(profile.features)
    header = [
        f"# Auto-generated by scripts/gen_requirements.py for profile "
        f"{profile.name!r}.",
        f"# Base: {base.name} (includes inlined).",
    ]
    if drop:
        header.append(f"# Dropped (profiled-out feature deps): "
                      f"{', '.join(sorted(drop))}.")
    else:
        header.append("# Dropped: nothing (profile admits every dep-bearing "
                      "feature).")
    if admitted is not None:
        header.append(f"# Admitted features: {', '.join(admitted)}.")
    header.append("")

    out: list = list(header)
    for raw, _origin in _iter_lines(base, set()):
        name = _dist_name(raw)
        if name is not None and _normalize(name) in drop:
            out.append(f"# [profile:{profile.name}] dropped — {raw.strip()}")
        else:
            out.append(raw)
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", required=True,
                    help="target profile name (profiles/<name>.toml) or a path")
    ap.add_argument("--base", default=None,
                    help="base requirements file (default: _Docs/requirements.txt)")
    ap.add_argument("--catalog", default=None,
                    help="full-app catalog (default: profiles/full.toml)")
    ap.add_argument("-o", "--output", default=None,
                    help="write here instead of stdout")
    args = ap.parse_args(argv)

    repo_root = _repo_root()
    sys.path.insert(0, str(repo_root))
    from well_viewer.core.profile import load_profile

    base = Path(args.base) if args.base else repo_root / "_Docs" / "requirements.txt"
    catalog_path = (Path(args.catalog) if args.catalog
                    else repo_root / "profiles" / "full.toml")
    catalog = list(tomllib.loads(
        catalog_path.read_text(encoding="utf-8")).get("feature") or [])
    profile = load_profile(args.profile)

    drop = excluded_pip_names(catalog, profile)
    text = generate(base, catalog, profile, drop)

    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
        print(f"Wrote {args.output} for profile {profile.name!r} "
              f"(dropped {len(drop)} dist(s): {', '.join(sorted(drop)) or '—'}).",
              file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
